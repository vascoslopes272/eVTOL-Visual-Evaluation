"""Assemble the draft Preliminary Analysis document from the index and the live tables.

``write_markdown`` walks :data:`index.GROUPS` / :data:`index.SECTIONS`, prints each
section's heading and three lines, then the tables and figures the index names for
it. The prose is the index's; every number comes from the tables. The user edits
the prose, never the numbers — a re-run regenerates the file.
"""

from __future__ import annotations

import datetime as _dt
from pathlib import Path
from typing import Dict, Optional

import pandas as pd

from . import index
from .loaders import Dataset

MAX_ROWS = 40


def _table_md(name: str, table: pd.DataFrame) -> str:
    t = table
    if isinstance(t.index, pd.MultiIndex) or t.index.name is not None:
        t = t.reset_index()
    note = ""
    if len(t) > MAX_ROWS:
        note = f"\n\n*First {MAX_ROWS} of {len(t)} rows; the full table is `{name}.csv`.*"
        t = t.head(MAX_ROWS)
    return f"**Table `{name}`**\n\n{t.to_markdown(index=False)}{note}\n"


def _figure_md(name: str, path: Path, out_dir: Path) -> str:
    rel = Path(path).relative_to(out_dir) if Path(path).is_relative_to(out_dir) else Path(path)
    return f"![{name}]({rel.as_posix()})\n\n*Figure `{name}`.*\n"


def write_markdown(ds: Dataset, tables: Dict[str, pd.DataFrame], figures: Dict[str, Path],
                   out_dir: Path, filename: str = "PRELIMINARY_ANALYSIS.md",
                   extra_notes: Optional[Dict[str, str]] = None) -> Path:
    """Write the draft; returns its path. ``extra_notes`` adds a paragraph under a section id."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    extra_notes = extra_notes or {}
    today = _dt.date.today().isoformat()
    lines = [
        f"# {index.TITLE}",
        "",
        f"Date: {today} · Generated by `labeling_evaluation/notebooks/30_preliminary_analysis.ipynb` "
        f"from `{ds.root.name}` · Source of the structure: the annotated index v1.1; source of "
        f"every number: the tables printed here.",
        "",
        "Each section carries three lines — **Source**, **Tables / figures**, **Gives →** — "
        "followed by the tables and figures it names. The prose is editable; the numbers are "
        "regenerated on every run and must not be typed by hand.",
        "",
        index.UNIT_NOTE,
        "",
        "---",
        "",
    ]
    if "block_diagram_all" in figures:
        lines += ["## Overview — what each section gives, and which chapter it feeds", "",
                  _figure_md("block_diagram_all", figures["block_diagram_all"], out_dir), ""]
        if "index_feeds" in tables:
            lines += [_table_md("index_feeds", tables["index_feeds"]), ""]
        lines += ["---", ""]

    for g in index.GROUPS:
        secs = index.sections_of(g["id"])
        if not secs:
            continue
        head = f"## {g['id']}. {g['title']}" if g["id"] != "A" else f"## {g['title']}"
        if g["chapter"]:
            head += f" ({g['chapter']})"
        lines += [head, ""]
        if g["id"] == "5" and "block_diagram_5" in figures:
            lines += ["Opening figure: purpose of each subsection and the analysis it feeds.", "",
                      _figure_md("block_diagram_5", figures["block_diagram_5"], out_dir), ""]
        for s in secs:
            lines += [index.heading(s["id"]), "", index.text(s["id"]), ""]
            if s["id"] in extra_notes:
                lines += [extra_notes[s["id"]], ""]
            for name in s["tables"]:
                if name in tables:
                    lines += [_table_md(name, tables[name]), ""]
                else:
                    lines += [f"*Table `{name}` not produced in this run.*", ""]
            for name in s["figures"]:
                if name in figures:
                    lines += [_figure_md(name, figures[name], out_dir), ""]
        lines += ["---", ""]

    lines += ["## Not in the preliminary analysis (by design)", "", index.NOT_IN_SCOPE, ""]
    path = out_dir / filename
    path.write_text("\n".join(lines), encoding="utf-8")
    return path
