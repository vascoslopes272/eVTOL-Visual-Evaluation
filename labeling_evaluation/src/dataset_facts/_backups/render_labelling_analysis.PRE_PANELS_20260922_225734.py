#!/usr/bin/env python3
"""Generate LABELLING_ANALYSIS.md, its figures, tables and PDF.

    python3 scripts/render_labelling_analysis.py [--pdf]

Tables and figures only (user ruling 2026-09-22), structured by ``src/dataset_facts/la_index.py``.
Reuses every Preliminary Analysis table (``export.build_all``) and adds the Labelling Analysis
ones (``la_tables.build_all``); figures come from ``la_figures.render_all``. Output goes to
``<preliminary output_dir>/../labelling_analysis/``.
"""
import datetime as dt
import subprocess
import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")

PILLAR = Path(__file__).resolve().parent.parent
REPO = PILLAR.parent
sys.path.insert(0, str(PILLAR))
from src.config_loader import load_config  # noqa: E402
from src.dataset_facts import export, la_figures, la_index, la_tables, load_dataset, numbers, report  # noqa: E402


def main(argv):
    cfg = load_config()
    facts = dict(cfg["dataset_facts"])
    facts.pop("conformance_dir", None)          # the codebook-rule run is not part of this document
    ds = load_dataset(cfg)
    out = Path(facts["output_dir"]).parent / "labelling_analysis"
    out.mkdir(parents=True, exist_ok=True)
    partial = facts.get("partial_window_start", 2024)
    values = numbers.live(ds, partial)
    tables = export.build_all(ds, facts)
    tables.update(la_tables.build_all(ds))
    figs = la_figures.render_all(ds, out, partial)
    export.write_all(tables, out)
    # every PNG prints at its drawn size (200 dpi, 7.09 in text width): a 7-pt letter stays 7 pt on paper
    from PIL import Image
    for name, fpath in figs.items():
        if str(fpath).endswith(".png") and name not in la_index.LANDSCAPE:
            with Image.open(fpath) as im:
                la_index.FIG_WIDTH[name] = f"{min(100, round(im.size[0] / 200 / 7.087 * 100))}%"
    generated = (f"Date: {dt.date.today().isoformat()} · Generated by "
                 f"`labeling_evaluation/scripts/render_labelling_analysis.py` from the master labels "
                 f"(notebook 04; PatSeer snapshot {values['snapshot']}) · Tables and figures only; every number "
                 "comes from `tables/`, the structure from `src/dataset_facts/la_index.py`, the AAM Reality Index "
                 "from `assets/external/aam_reality_index/`.")
    md = report.write_markdown(ds, tables, figs, out, filename="LABELLING_ANALYSIS.md", values=values,
                               partial_window_start=partial, idx=la_index, generated_by=generated,
                               keep_with_next=True)
    print(f"tables={len(tables)}  figures={len(figs)}")
    print(f"document: {md}  ({md.stat().st_size / 1024:.0f} KB)")
    if "--pdf" in argv:
        pdf = md.with_suffix(".pdf")
        subprocess.run([sys.executable, str(REPO / "scripts" / "build_styled_md_pdf.py"),
                        str(md), str(pdf), "--compact"], check=True)
        pages = subprocess.run(["pdfinfo", str(pdf)], capture_output=True, text=True).stdout
        print(pdf.name, [l for l in pages.splitlines() if l.startswith("Pages")])


if __name__ == "__main__":
    main(sys.argv[1:])
