"""Write thesis_figures_v2/Part_I_evidence_base/README.md from viz/thesis_v2_part1.ITEMS and the config's
architecture fold. Run standalone (python3 notebooks/_build/write_readme_48.py) or from notebook 48, after
the items are written.
"""
from __future__ import annotations

import sys
from pathlib import Path

PILLAR = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(PILLAR))

from viz import config, style
from viz import thesis_v2_part1 as v2

cfg = config.load()
OUT = v2.out_root(cfg)
fold = cfg.analysis["class_fold"]   # 12-architecture code -> 5-group code, e.g. "TR": "VT"

GROUP_ORDER = ["I1_patenting_rate", "I2_active_protection", "I3_construct_validity", "I4_external_validity"]
GROUP_TITLE = {"I1_patenting_rate": "I1. Patenting rate", "I2_active_protection": "I2. Active protection",
               "I3_construct_validity": "I3. Construct validity", "I4_external_validity": "I4. External validity"}
ROLE_ORDER = ["main", "auxiliary", "appendix"]

lines = []
lines.append("# Part I (Evidence base) figures, v2\n")
lines.append("Reorganised, relabelled and simplified versions of a subset of the Q1 / Q4 / Q5 thesis figures "
             "(`viz/thesis_v2_part1.py`). No number or computation is changed from `thesis_figures/`, a sibling "
             "folder this one never writes into; every builder reads its frame from `viz/thesis_q1.py`, "
             "`thesis_q4.py` or `thesis_q5.py` unchanged and only re-draws, relabels or regroups it. Generated by "
             "`notebooks/48_thesis_figures_v2_part1.ipynb`.\n")

lines.append("## Terminology\n")
lines.append("- \"unique aircraft\" -> **designs**; \"aircraft\" as a counted unit -> **designs**")
lines.append("- \"labelled dataset\" -> **patent dataset**; \"labelled\", \"coded\", \"coding\", \"corpus\" -> never used")
lines.append("- \"class\" -> **architecture**; a combination of attributes -> **archetype**")
lines.append("- patents are counted as **patent families**")
lines.append("- architecture short codes: only the twelve below; **SLC** replaces \"L+C\" / \"LC\" everywhere a "
             "short code is printed\n")

lines.append("## The twelve architectures and the five folded groups\n")
lines.append("`labelling_analysis.yaml`'s `analysis.class_fold` folds the twelve architectures (patent-dataset "
             "codes) into the five groups the evtol.news directory uses, for the class-mix and dataset-vs-directory "
             "figures (I4). TR displays as **TP** (Tilt Propulsor) and TB as **TF** (Tilt Frame) — both display-only "
             "overrides of the underlying codes, confirmed by the author 2026-10-10; the data codes themselves "
             "(TR, TB) are unchanged.\n")
lines.append("| architecture (code) | printed name | folds into |")
lines.append("|---|---|---|")
for code in style.CLASS_ORDER:
    s = v2.arch(code)
    short = v2.ARCH_SHORT_OVERRIDE.get(code, s.short)
    group = fold.get(code, "")
    group_name = v2.GROUP_NAME.get(group, "")
    lines.append(f"| {short} | {s.name} | {group} — {group_name} |" if group else f"| {short} | {s.name} | (not folded) |")
lines.append("")
lines.append("| folded group | printed name |")
lines.append("|---|---|")
for g in ["VT", "LC", "WM", "ER", "HB"]:
    lines.append(f"| {g} | {v2.GROUP_NAME[g]} |")
lines.append("")

lines.append("## Files\n")
lines.append("One line per file: its role (main / auxiliary / appendix) and the sub-question it answers. Each "
             "figure's source data sits beside it as `<name>.csv`, with `<name>.json` carrying the title and where "
             "it comes from in the original `thesis_figures/`.\n")
for gkey in GROUP_ORDER:
    lines.append(f"### {GROUP_TITLE[gkey]}\n")
    for role in ROLE_ORDER:
        its = [it for it in v2.ITEMS if it["group"] == gkey and it["role"] == role]
        if not its:
            continue
        lines.append(f"**{role}**")
        for it in its:
            kind = "table" if it["kind"] == "table" else "figure"
            lines.append(f"- `{it['name']}` ({kind}) — {it['title']} *(from {it['source_item']})*")
        lines.append("")

lines.append("## Not copied (dropped from Part I)\n")
lines.append("- `q4_trl_by_class` — kept in the full `thesis_figures/Q4_representativeness/appendix/`, out of scope here")
lines.append("- `q4_name_coverage` — kept in the full `thesis_figures/Q4_representativeness/appendix/`, out of scope here\n")

lines.append("## q1_na_drop_is_real: two versions, pending a choice\n")
lines.append("`I1_patenting_rate/auxiliary/` holds **both** `q1_na_drop_is_real_A` (the original stacked bars, "
             "rotated % labels removed, North America's share added as a line on its own axis, read through 2023 "
             "only — the years with 8 or more designs) and `q1_na_drop_is_real_B` (the bars replaced entirely by "
             "that line). Drop whichever the author does not keep.\n")

lines.append("## Number checks (2026-10-10, no numbers changed)\n")
lines.append("- `q4_coding_agreement`: the current build says **87 of 97** (drawing label against the public "
             "aircraft), matching `thesis_document/main.tex`. \"88 of 98\" is from the older preliminary brief "
             "(`labelling_analysis_preliminary/LABELLING_ANALYSIS_FOR_REVIEW.md`), not the thesis.")
lines.append("- `q1_growth_rates` / `q1_growth_rates_table`: the current doubling time for eVTOL architecture "
             "patents is **3.6 years**, matching `main.tex`. \"3.8\" is likewise from the older preliminary brief.\n")

lines.append("## Source limits of the evtol.news inputs\n")
lines.append("- The evtol.news text used here (directory pages, development years, domain spec sheets) is the **public, non-member "
             "view**: 1 138 of the 1 229 crawled pages end with \"VFS Member? Log in to read more!\", so VFS-member-only content "
             "(probably more Resources entries) is missing. A year read from this text is an upper bound of when the aircraft "
             "first existed (\"existed by\" = a prototype existed by then, even if sub-scale), not a start date.")
lines.append("- Domain flag of the directory pages (rulings 2026-10-11): a power source offering an electric version counts as "
             "electric; only unmanned pages (cargo-only, no passengers, cargo drone) are UAVs; autonomous or remote pages count as "
             "piloted; hybrid-electric is not an electric option; an uncrewed demonstrator is out; the author's single-page rulings "
             "(review/domain_overrides.csv) override the rules. It applies to the evtol.news side only; the patent dataset's own domain gate is unchanged.\n")

lines.append("- External inputs (2026-10-11): the evtol.news development year, the TRL and the AAM Reality Index company map are set by "
             "rule-based scripts with no model (`viz/script_inputs.py`, lists in `review/script_outputs/`, written by notebook 60); "
             "where the author read an item in the review, his value is used. Agreement of each script with the author: notebook 60.\n")
lines.append("- Kinds of date used in the year review: **announced / unveiled** = presented as a project in order to start being developed (an already built aircraft shown is \"existed by\"); **existed by** = a prototype existed by then, even if sub-scale; a concept design has neither flown nor has a prototype.\n")

lines.append("## Judgement calls flagged for review\n")
lines.append("- The six sector events kept on `q1_filings_per_year` (main slot only): EHang 184 "
             "unveiled, Uber Elevate white paper, EASA SC-VTOL, COVID-19 pandemic declared, SPAC listings, first uncrewed eVTOL type certificate — chosen for spread "
             "across the timeline; not a stated criterion.")
lines.append("- `q1_growth_rates_table`'s old \"families 2005-2023\" column is renamed \"count 2005-2023\" "
             "(neutral), since the eVTOL unique-designs row counts designs, not patent families.")
lines.append("- `q4_coding_agreement` / `q4_flown_representativeness` / `q4_flown_index_firm_representativeness`: \"folded "
             "class\" -> **architecture group**, and \"configuration\" / \"class\" -> **architecture** in the "
             "disagreement notes (step 2's naming rules, applied by inference since neither term was given "
             "explicitly for these spots).\n")

(OUT / "README.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("written", OUT / "README.md")
